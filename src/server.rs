//! The MCP server: its setup, the instructions it sends, and cancelling tool
//! calls. The tools are in `tools`.

use std::sync::Arc;

use rmcp::handler::server::router::tool::ToolRouter;
use rmcp::handler::server::tool::ToolCallContext;
use rmcp::model::{
    CallToolRequestParams, CallToolResponse, CallToolResult, ContentBlock, Implementation,
    ServerCapabilities, ServerConfig,
};
use rmcp::service::RequestContext;
use rmcp::{ErrorData, RoleServer, ServerHandler, tool_handler};
use tokio::sync::Mutex;

use crate::tools;

/// The server instructions, from `instructions.md`. The file's text is sent
/// as-is, apart from trailing whitespace being trimmed. So keep each
/// paragraph on one line, and don't add comments: they would be sent too.
pub const INSTRUCTIONS: &str = include_str!("instructions.md").trim_ascii_end();

#[derive(Clone)]
pub struct JjServer {
    /// An async mutex, so `jj_set_default_revision` can hold it while it
    /// checks the new value. Calls then see the default in the order they
    /// were made, not the order their `jj log` checks finished.
    pub(crate) default_revision: Arc<Mutex<Option<String>>>,
    tool_router: ToolRouter<Self>,
}

impl JjServer {
    pub fn new() -> Self {
        Self {
            default_revision: Arc::default(),
            tool_router: tools::router(),
        }
    }
}

#[tool_handler(router = self.tool_router)]
#[allow(
    clippy::unused_async_trait_impl,
    reason = "the async fns are generated by `tool_handler`"
)]
impl ServerHandler for JjServer {
    fn get_info(&self) -> ServerConfig {
        ServerConfig::new(ServerCapabilities::builder().enable_tools().build())
            .with_server_info(Implementation::new(
                env!("CARGO_PKG_NAME"),
                env!("CARGO_PKG_VERSION"),
            ))
            .with_instructions(INSTRUCTIONS)
    }

    /// Replaces the `call_tool` that `tool_handler` would generate, to stop
    /// the tool when the client cancels the call. rmcp only cancels a token,
    /// so without this the tool's jj process runs to the end. Dropping the
    /// tool's future kills it.
    async fn call_tool(
        &self,
        request: CallToolRequestParams,
        context: RequestContext<RoleServer>,
    ) -> Result<CallToolResponse, ErrorData> {
        let cancelled = context.ct.clone();
        let call = self
            .tool_router
            .call(ToolCallContext::new(self, request, context));
        tokio::select! {
            result = call => result,
            () = cancelled.cancelled() => {
                Ok(CallToolResult::error(vec![ContentBlock::text("Cancelled.")]).into())
            }
        }
    }
}
